import type { Candidate } from "./types";
import { analyzeCandidate } from "./scoring";

function build(
  partial: Omit<
    Candidate,
    | "ai_score"
    | "ai_score_label"
    | "ai_score_color"
    | "ai_summary"
    | "ai_result"
    | "created_at"
    | "updated_at"
  > & { created_at?: string }
): Candidate {
  const result = analyzeCandidate({
    full_name: partial.full_name,
    email: partial.email,
    country: partial.country,
    timezone: partial.timezone,
    main_role: partial.main_role,
    secondary_role: partial.secondary_role,
    years_experience: partial.years_experience,
    expected_monthly_salary_usd: partial.expected_monthly_salary_usd,
    expected_hourly_rate_usd: partial.expected_hourly_rate_usd,
    availability: partial.availability,
    remote_preference: partial.remote_preference,
    skills: partial.skills,
    tools: partial.tools,
    languages: partial.languages,
    portfolio_url: partial.portfolio_url,
    linkedin_url: partial.linkedin_url,
    github_url: partial.github_url,
    twitter_url: partial.twitter_url,
    website_url: partial.website_url,
    bio: partial.bio,
    work_samples: partial.work_samples,
    preferred_industries: partial.preferred_industries,
    open_to_relocate: partial.open_to_relocate,
    public_profile_enabled: partial.public_profile_enabled,
    cv_text: partial.cv_text,
  });

  const now = partial.created_at || new Date().toISOString();
  return {
    ...partial,
    ai_score: result.overall_score,
    ai_score_label: result.score_label,
    ai_score_color: result.score_color,
    ai_summary: result.share_card_summary,
    ai_result: result,
    created_at: now,
    updated_at: now,
  };
}

